"""Rebuild source illustration sheets. Optional tool: pip install pymupdf.

Run from the repository root; the original user-supplied PDF is never modified.
Only diagram sheets are exported, not the full text of the book.
"""
from pathlib import Path
import pymupdf

source = next(Path.cwd().glob("Yiannis Papadopoulos*.pdf"))
destination = Path("public/book")
destination.mkdir(parents=True, exist_ok=True)
pages = [*range(20, 27), *range(28, 35), *range(36, 43), *range(44, 51),
         *range(54, 58), *range(59, 65), *range(67, 74), *range(75, 82), *range(83, 94)]
dimensions = []
with pymupdf.open(source) as document:
    for number in pages:
        page = document[number - 1]
        # Retain headings, formulas and all figures. Drop 3 tips are taught in
        # original lesson prose, so omit those paragraphs below the diagrams.
        bottom = page.rect.height - 61
        if 75 <= number <= 81:
            paragraphs = [block[1] for block in page.get_text("blocks")
                          if block[1] > 500 and len(block[4].strip()) > 180]
            if paragraphs:
                bottom = min(bottom, min(paragraphs) - 8)
        crop = pymupdf.Rect(30, 65, page.rect.width - 30, bottom)
        pixmap = page.get_pixmap(matrix=pymupdf.Matrix(2.5, 2.5), clip=crop, alpha=False)
        pixmap.pil_save(str(destination / f"{number:03}.webp"), format="WEBP", quality=88)
        dimensions.append(f"  {number}: {{ width: {pixmap.width}, height: {pixmap.height} }},")
Path("lib/content/book-diagram-sizes.ts").write_text(
    "// Generated by scripts/extract-book-diagrams.py.\n"
    "export const DIAGRAM_SIZES: Record<number, { width: number; height: number }> = {\n"
    + "\n".join(dimensions) + "\n};\n", encoding="utf-8")
print(f"Exported {len(pages)} credited source diagram sheets to {destination}.")
